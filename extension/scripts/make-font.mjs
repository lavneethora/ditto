/**
 * Generates src/ui/geist-mono.ts, the Geist Mono wordmark face inlined as a
 * data URL.
 *
 * Inlined rather than linked because the drawer runs inside a host page: a
 * chrome-extension:// font URL depends on the page's CSP and on the file being
 * web-accessible, and a Google Fonts URL depends on the page's CSP too. A data
 * URL registered through the FontFace API depends on neither.
 *
 * Run: node scripts/make-font.mjs
 */
import { readFileSync, writeFileSync } from "node:fs"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
const source = resolve(
  here,
  "../node_modules/geist/dist/fonts/geist-mono/GeistMono-SemiBold.woff2"
)
const out = resolve(here, "../src/ui/geist-mono.ts")

const base64 = readFileSync(source).toString("base64")

const lines = [
  "// GENERATED by scripts/make-font.mjs. Do not edit by hand.",
  "//",
  "// Geist Mono SemiBold, inlined as a data URL for the Ditto wordmark.",
  "",
  "/**",
  " * Registers the face on the document.",
  " *",
  " * This uses the FontFace API rather than an at-font-face CSS rule because",
  " * the drawer renders inside a shadow root, and Chrome ignores at-font-face",
  " * declared inside one: font faces are document-scoped. A face added to",
  " * document.fonts is visible to the shadow tree; a face declared in the",
  " * shadow tree's own stylesheet is not.",
  " *",
  " * Safe to call repeatedly, and safe to call on a page that forbids it. A",
  " * failure here costs the wordmark its font and nothing else.",
  " */",
  "export async function loadGeistMono(): Promise<void> {",
  "  try {",
  '    if (typeof document === "undefined" || !document.fonts) return',
  "",
  "    for (const face of document.fonts) {",
  '      if (face.family === "Geist Mono") return',
  "    }",
  "",
  "    const face = new FontFace(",
  '      "Geist Mono",',
  "      `url(data:font/woff2;base64," + base64 + ') format("woff2")`,',
  '      { weight: "600", style: "normal", display: "swap" }',
  "    )",
  "",
  "    document.fonts.add(await face.load())",
  "  } catch {",
  "    // The wordmark falls back to the monospace stack in styles.css.",
  "  }",
  "}",
  ""
]

writeFileSync(out, lines.join("\n"))
console.log(`wrote ${out} (${(lines.join("\n").length / 1024).toFixed(0)}KB)`)
